"""Builds CHarth/Music.h: an original 16 bar psytrance-style loop for the one-voice piezo, about 150 BPM.

Notes are MIDI numbers, lengths are in 50 ms units (a sixteenth is 2: 100 ms). Bars 1-4 and 9-12: a rolling
offbeat bass (a gap on each beat where the kick would be, then three bass notes, the last an octave up).
Bars 5-8: fast arpeggios over the same chords. Bars 13-16: a melody in a phrygian, eastern-sounding mode.
"""
import os
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
notes = []

def bass(root, octave_pattern=(0, 0, 12)):
    for _ in range(4):
        notes.extend([(0, 2)] + [(root + o, 2) for o in octave_pattern])

def arp(root, third, fifth):
    seq = [root, third, fifth, third + 12]
    for _ in range(4):
        for n in seq: notes.append((n + 12, 2))

def phrase(seq):                                   # (note, sixteenths) pairs filling one bar of 16
    for n, l in seq: notes.append((n, 2 * l))

A, C, E, F, G, B = 69, 72, 76, 65, 67, 71
for r in (A, A, F, G): bass(r)                                           # 1-4
for r, t, f in ((A, C, E), (A, C, E), (F, A, C + 12), (G, B, 74)): arp(r, t, f)   # 5-8
for r in (A, C, F, G): bass(r, (0, 12, 0))                               # 9-12
phrase([(88, 6), (89, 2), (88, 2), (84, 2), (86, 2), (0, 2)])            # 13: E F E C D
phrase([(84, 4), (81, 2), (84, 2), (88, 4), (89, 2), (88, 2)])           # 14
phrase([(91, 6), (89, 2), (88, 2), (86, 2), (88, 2), (0, 2)])            # 15
phrase([(88, 2), (89, 2), (88, 2), (84, 2), (81, 4), (76, 4)])           # 16

assert sum(l for _, l in notes) == 16 * 16 * 2 * 1, sum(l for _, l in notes)
flat = ", ".join("%d,%d" % n for n in notes)
out = ["// GENERATED by tools/music.py: an original psytrance-style loop, ~150 BPM, 16 bars (MIDI note, length in 50 ms).",
       "#pragma once", "#include <stdint.h>", "",
       "static const uint8_t PSY_TUNE[] = { %s };" % flat]
open("CHarth/Music.h", "w", newline="").write("\n".join(out) + "\n")
print(len(notes), "notes,", sum(l for _, l in notes) * 50 / 1000, "s per loop")
