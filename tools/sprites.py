import os, json
from PIL import Image
os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
# char -> game palette index
IDX = {'.': 255, 'a': 1, 'A': 5, 'b': 9, 'w': 13, 'g': 2, 'G': 6, 'h': 10, 'r': 4, 'R': 8, 's': 12, 'c': 3, 'C': 7, 'd': 11}
PAL = [(6,10,6),(255,176,0),(53,255,112),(64,216,224),(255,75,43),(255,217,138),(180,255,200),(184,244,248),(255,176,154),
       (122,82,0),(15,122,48),(18,106,112),(138,30,10),(255,200,87),(22,34,22),(184,168,120)]
SPR = {
 "TILE": ["AAAAAb", "Aaaaab", "AaAaab", "Aaaaab", "Aaaaab", "bbbbbb"],
 "SHIP0": ["..ww..", ".wccw.", ".wccw.", "wwwwww", "wd..dw", "..rr.."],
 "SHIP1": ["..ww..", ".wccw.", ".wccw.", "wwwwww", "wd..dw", "..RR.."],
 "EXP0": ["......", ".AAAA.", ".Awwb.", ".Awwb.", ".AbbA.", "......"],
 "EXP1": ["A.AA.A", ".AwwA.", "AwwwwA", "AwwwwA", ".AwwA.", "A.AA.A"],
 "EXP2": ["w....w", "..AA..", ".A..A.", ".A..A.", "..AA..", "w....w"],
 "MUZ0": ["..AA..", ".AwwA.", "AwwwwA", "..ww..", "......", "......"],
 "MUZ1": ["......", "..AA..", ".AwwA.", "..AA..", "......", "......"],
 "MUZ2": ["......", "......", "..ww..", "......", "......", "......"],
}
out = ["// GENERATED by tools/sprites.py: 6x6 sprites drawn with the pixel-art tool (art/sprites.png).",
       "// One byte a pixel: a game palette index, 255 transparent.", "#pragma once", "#include <stdint.h>", ""]
for name, rows in SPR.items():
    assert len(rows) == 6 and all(len(r) == 6 for r in rows), name
    out.append("static const uint8_t %s[36] = { %s };" % (name, ", ".join(str(IDX[c]) for r in rows for c in r)))
open("CHarth/Sprites.h", "w", newline="").write("\n".join(out) + "\n")
pix = []
for i, (name, rows) in enumerate(SPR.items()):
    for y, r in enumerate(rows):
        for x, c in enumerate(r):
            if c != '.':
                rr, gg, bb = PAL[IDX[c]]
                pix.append({"x": x + i * 7, "y": y, "color": "#%02X%02X%02X" % (rr, gg, bb)})
json.dump({"width": 7 * len(SPR) - 1, "height": 6, "background": "#060A06", "pixel_size": 20, "pixels": pix}, open("art/sprites.json", "w"))
# Preview at 20x: one square per pixel on the background colour.
img = Image.new("RGB", (20 * (7 * len(SPR) - 1), 20 * 6), (6, 10, 6))
for p in pix:
    x, y = 20 * p["x"], 20 * p["y"]
    img.paste(p["color"], (x, y, x + 20, y + 20))
img.save("art/sprites.png")
